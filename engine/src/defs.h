[[nodiscard]] constexpr Move pack_move(uint8_t src, uint8_t dst,
                                       uint8_t kind = MoveTypes::Normal) noexcept {
  const unsigned packed =
      ((static_cast<unsigned>(src) & 0x3FU) << 10U) |
      ((static_cast<unsigned>(dst) & 0x3FU) << 4U) |
      (static_cast<unsigned>(kind) & 0x03U);
  return static_cast<Move>(packed);
}

[[nodiscard]] constexpr Move pack_move_promo(uint8_t src, uint8_t dst,
                                             uint8_t promo_kind) noexcept {
  const unsigned packed =
      ((static_cast<unsigned>(src) & 0x3FU) << 10U) |
      ((static_cast<unsigned>(dst) & 0x3FU) << 4U) |
      ((static_cast<unsigned>(promo_kind) & 0x03U) << 2U) |
      static_cast<unsigned>(MoveTypes::Promotion);
  return static_cast<Move>(packed);
}

