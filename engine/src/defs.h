struct MoveInfo {
  std::array<Move, ListSize> moves{};
  std::array<int, ListSize> scores{};
  uint16_t len{0};
};

// Scratch storage is reused per live move picker, outside the OS thread stack.
struct MoveBuffers {
  MoveInfo captures;
  MoveInfo quiets;
  MoveInfo bad_captures;
  std::array<Move, ListSize> quiet_history{};
  std::array<Move, ListSize> capture_history{};
};

class MoveBufferPool {
  std::vector<std::unique_ptr<MoveBuffers>> pool_slots_;
  size_t active_depth_{0};

 public:
  MoveBufferPool() = default;
  // Helper threads own their scratch storage; it is never shared or copied.
  MoveBufferPool(const MoveBufferPool &) {}
  MoveBufferPool &operator=(const MoveBufferPool &) {
    assert(active_depth_ == 0);
    return *this;
  }

  MoveBuffers &acquire() {
    if (active_depth_ == pool_slots_.size()) {
      pool_slots_.push_back(std::make_unique<MoveBuffers>());
    }
    return *pool_slots_[active_depth_++];
  }

  void release() noexcept {
    assert(active_depth_ > 0);
    --active_depth_;
  }
};

class MoveBufferLease {
  MoveBufferPool &owner_;

 public:
  MoveBuffers &buffers;

  explicit MoveBufferLease(MoveBufferPool &pool)
      : owner_(pool), buffers(pool.acquire()) {}
  ~MoveBufferLease() { owner_.release(); }

  MoveBufferLease(const MoveBufferLease &) = delete;
  MoveBufferLease &operator=(const MoveBufferLease &) = delete;
};

